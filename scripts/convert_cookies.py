"""Convert browser-exported cookies (JSON) to Netscape cookies.txt for yt-dlp.

Usage:
    1. Save your browser-exported cookies JSON to backend/cookies_input.json
    2. Run: python scripts/convert_cookies.py
    3. The script writes backend/cookies.txt and deletes cookies_input.json

NEVER commit cookies_input.json or cookies.txt (both are gitignored).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "backend" / "cookies_input.json"
OUTPUT = ROOT / "backend" / "cookies.txt"


def main() -> None:
    if not INPUT.is_file():
        raise SystemExit(f"Missing {INPUT}. Save your exported cookies JSON there first.")

    data = json.loads(INPUT.read_text(encoding="utf-8"))
    if not isinstance(data, list):
        raise SystemExit("Expected a JSON array of cookie objects.")

    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by scripts/convert_cookies.py for yt-dlp --cookies.",
        "# Do NOT commit this file. It contains session credentials.",
        "",
    ]
    for c in data:
        domain = c.get("domain", "")
        if not domain:
            continue
        host_only = bool(c.get("hostOnly", False))
        flag = "FALSE" if host_only else "TRUE"
        path = c.get("path", "/") or "/"
        secure = "TRUE" if c.get("secure", False) else "FALSE"
        if c.get("session", False):
            expires = 0
        else:
            expires = int(c.get("expirationDate", 0) or 0)
        name = c.get("name", "")
        value = c.get("value", "")
        if not name:
            continue
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # Remove the raw JSON input so secrets don't linger.
    INPUT.unlink(missing_ok=True)
    print(f"Wrote {OUTPUT} ({len(lines) - 4} cookies). Input JSON removed.")


if __name__ == "__main__":
    main()
